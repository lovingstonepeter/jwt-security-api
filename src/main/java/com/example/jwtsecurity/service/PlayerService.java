package com.example.jwtsecurity.service;

import com.example.jwtsecurity.dto.PlayerRequest;
import com.example.jwtsecurity.dto.PlayerResponse;
import com.example.jwtsecurity.entity.Player;
import com.example.jwtsecurity.exception.PlayerNotFoundException;
import com.example.jwtsecurity.repository.PlayerRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
public class PlayerService {
    private final PlayerRepository playerRepository;

    public PlayerService(PlayerRepository playerRepository) {
        this.playerRepository = playerRepository;
    }

    @Transactional(readOnly = true)
    public List<PlayerResponse> getAllPlayers() {
        return playerRepository.findAll().stream().map(PlayerResponse::from).toList();
    }

    @Transactional(readOnly = true)
    public PlayerResponse getPlayerById(Long id) {
        return PlayerResponse.from(findById(id));
    }

    @Transactional
    public PlayerResponse addPlayer(PlayerRequest request) {
        Player player = new Player();
        apply(player, request);
        return PlayerResponse.from(playerRepository.save(player));
    }

    @Transactional
    public PlayerResponse updatePlayerById(Long id, PlayerRequest request) {
        Player player = findById(id);
        apply(player, request);
        return PlayerResponse.from(playerRepository.save(player));
    }

    @Transactional
    public void deletePlayerById(Long id) {
        playerRepository.delete(findById(id));
    }

    private Player findById(Long id) {
        return playerRepository.findById(id)
                .orElseThrow(() -> new PlayerNotFoundException("Player with id " + id + " not found"));
    }

    // The id is never copied from the request: it is generated by the database.
    private void apply(Player player, PlayerRequest request) {
        player.setName(request.name());
        player.setJerseyNumber(request.jerseyNumber());
        player.setPosition(request.position());
    }
}
